  function policyRuleHTML(rule, kindLabel = "") {
    if (!rule) return "";
    const targets = (rule.targets || []).map((target) => target.label).join("、");
    const assignee = (rule.assignee || []).map((party) => party.label).join("、");
    const constraints = (rule.constraints || [])
      .map((constraint) => `<li>${esc(constraint)}</li>`)
      .join("");
    const duties = (rule.duties || [])
      .map(
        (duty) =>
          `<p><b>${esc((duty.actions || []).map((action) => action.label).join(" / "))}</b>${duty.targets && duty.targets.length ? ` · ${esc(duty.targets.map((target) => target.label).join("、"))}` : ""}</p>`
      )
      .join("");
    const remedies = (rule.remedy || [])
      .map((remedy) => `<p><b>补救</b> · ${esc((remedy.actions || []).map((action) => action.label).join(" / "))}</p>`)
      .join("");
    return `
      <div class="policy-rule">
        ${kindLabel ? `<div class="policy-rule-kind">${esc(kindLabel)}</div>` : ""}
        ${policyActionHTML(rule.actions)}
        ${targets ? `<p class="policy-target"><b>对象</b> ${esc(targets)}${assignee ? ` · <b>被授权方</b> ${esc(assignee)}` : ""}</p>` : ""}
        ${constraints ? `<ul class="constraint-list">${constraints}</ul>` : ""}
        ${duties || remedies ? `<div class="duty-list"><span>义务 / 补救</span>${duties}${remedies}</div>` : ""}
      </div>`;
  }

  function policyRulesHTML(rules, kind) {
    if (!rules || !rules.length) return `<p class="policy-empty">无</p>`;
    return rules.map((rule) => policyRuleHTML(rule, kind)).join("");
  }

  function collectPolicyDuties(policy) {
    const duties = [];
    const seen = new Set();
    const add = (rule) => {
      if (!rule) return;
      const marker = JSON.stringify([rule.actions, rule.targets, rule.constraints]);
      if (seen.has(marker)) return;
      seen.add(marker);
      duties.push(rule);
    };
    (policy.obligations || []).forEach(add);
    (policy.permissions || []).forEach((permission) => (permission.duties || []).forEach(add));
    (policy.prohibitions || []).forEach((prohibition) => (prohibition.remedy || []).forEach(add));
    return duties;
  }

