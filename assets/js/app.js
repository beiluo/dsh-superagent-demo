  function conceptTreeHTML(concepts, query) {
    const normalized = query.trim().toLowerCase();
    const renderNode = (concept) => {
      const children = (concept.narrower || [])
        .map((ref) => conceptById.get(ref.id))
        .filter(Boolean)
        .map(renderNode)
        .filter(Boolean);
      const haystack = `${labelOf(concept)} ${labelEnOf(concept)} ${concept.definition || ""} ${concept.notation || ""}`.toLowerCase();
      const selfMatch = !normalized || haystack.includes(normalized);
      if (!selfMatch && !children.length) return "";
      const isActive = concept.id === state.conceptId;
      return `
        <li class="concept-node" data-concept-id="${esc(concept.id)}">
          <button class="concept-btn${isActive ? " is-active" : ""}${children.length ? "" : " is-leaf"}" type="button" data-concept="${esc(concept.id)}">
            <span class="concept-caret" aria-hidden="true">▾</span>
            <span class="concept-btn-label">${esc(labelOf(concept))}</span>
            <span class="concept-btn-notation">${esc(concept.notation || "")}</span>
          </button>
          ${children.length ? `<ul class="concept-list">${children.join("")}</ul>` : ""}
        </li>`;
    };
    return concepts.map(renderNode).filter(Boolean).join("");
  }

