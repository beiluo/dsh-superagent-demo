    if (!tooltip || !stage) return;
    const rect = stage.getBoundingClientRect();
    const clusterLabel = node.kind === "concept"
      ? (GRAPH_SCHEMES[node.cluster]?.label || node.cluster)
      : (GRAPH_CLUSTERS[node.cluster]?.label || node.cluster);
