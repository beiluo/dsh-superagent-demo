  function bindExplorer() {
    const search = $("#ontology-search");
    if (search) {
      search.addEventListener("input", () => {
        state.query = search.value;
        renderEntityList();
      });
    }

    const filters = $("#type-filters");
    if (filters) {
      filters.addEventListener("click", (event) => {
        const button = event.target.closest("[data-filter]");
        if (!button) return;
        state.filter = button.dataset.filter;
        syncFilterChips();
        renderEntityList();
      });
    }

    const layer = $("#layer-filter");
    if (layer) {
      layer.addEventListener("change", () => {
        state.layer = layer.value;
        renderEntityList();
      });
    }

    const list = $("#entity-list");
    if (list) {
      list.addEventListener("click", (event) => {
        const row = event.target.closest("[data-key]");
        if (!row) return;
        selectEntity(row.dataset.key);
      });
    }

    const reset = $("#reset-filters");
    if (reset) {
      reset.addEventListener("click", () => {
        state.filter = "all";
        state.layer = "all";
        state.query = "";
        if (search) search.value = "";
        syncFilterChips();
        renderEntityList();
      });
    }

    const detail = $("#detail-panel");
    if (detail) {
      detail.addEventListener("click", (event) => {
        if (event.target.closest("[data-copy]")) {
          copyText(event.target.closest("[data-copy]").dataset.copy);
        }
        if (event.target.closest("[data-close-detail]")) closeDetail();
      });
    }

    document.addEventListener("keydown", (event) => {
      if (event.key === "/" && !/INPUT|TEXTAREA|SELECT/.test(document.activeElement.tagName)) {
        event.preventDefault();
        search?.focus();
      }
      if (event.key === "Escape") {
        closeDetail();
        $("#site-nav")?.classList.remove("is-open");
        $("#nav-toggle")?.setAttribute("aria-expanded", "false");
        document.body.classList.remove("nav-open");
      }
    });
  }

  function bindTaxonomy() {
    const search = $("#concept-search");
    if (search) {
      search.addEventListener("input", () => {
        state.conceptQuery = search.value;
        renderConceptTree();
      });
    }

    const tree = $("#concept-tree");
    if (tree) {
      tree.addEventListener("click", (event) => {
        const caret = event.target.closest(".concept-caret");
        if (caret) {
          event.preventDefault();
          event.stopPropagation();
          caret.closest(".concept-node")?.classList.toggle("is-collapsed");
          return;
        }
        const button = event.target.closest("[data-concept]");
        if (button) selectConcept(button.dataset.concept);
      });
    }

    const detail = $("#concept-detail");
    if (detail) {
      detail.addEventListener("click", (event) => {
        const button = event.target.closest("[data-concept-jump]");
        if (button) selectConcept(button.dataset.conceptJump);
      });
    }
  }

  function bindRules() {
    const filters = $("#rule-filters");
    if (!filters) return;
    filters.addEventListener("click", (event) => {
      const button = event.target.closest("[data-severity]");
      if (!button) return;
      state.ruleSeverity = button.dataset.severity;
      $$("#rule-filters [data-severity]").forEach((item) => item.classList.toggle("is-active", item === button));
      renderRules();
    });
  }

  function bindNav() {
    const toggle = $("#nav-toggle");
    const nav = $("#site-nav");
    if (toggle && nav) {
      toggle.addEventListener("click", () => {
        const open = nav.classList.toggle("is-open");
        toggle.setAttribute("aria-expanded", String(open));
        document.body.classList.toggle("nav-open", open);
      });
      nav.addEventListener("click", (event) => {
        if (event.target.closest("a")) {
          nav.classList.remove("is-open");
          toggle.setAttribute("aria-expanded", "false");
          document.body.classList.remove("nav-open");
        }
      });
    }

    const sections = $$("main section[id]");
    if ("IntersectionObserver" in window && sections.length) {
      const observer = new IntersectionObserver(
        (entries) => {
          entries.forEach((entry) => {
            if (!entry.isIntersecting) return;
            $$(".site-nav a").forEach((link) => {
              link.classList.toggle("is-active", link.getAttribute("href") === `#${entry.target.id}`);
            });
          });
        },
        { rootMargin: "-30% 0px -58% 0px", threshold: 0 }
      );
      sections.forEach((section) => observer.observe(section));
    }

    const header = $("#site-header");
    if (header) {
      const onScroll = () => header.classList.toggle("is-scrolled", window.scrollY > 12);
      onScroll();
      window.addEventListener("scroll", onScroll, { passive: true });
    }
  }

  function bindHash() {
    const parse = () => {
      const hash = decodeURIComponent(window.location.hash.replace(/^#/, ""));
      if (hash.startsWith("entity=")) {
        const key = hash.slice("entity=".length);
        if (entityByKey.has(key)) {
          state.filter = "all";
          state.layer = "all";
          state.query = "";
          const search = $("#ontology-search");
          if (search) search.value = "";
          syncFilterChips();
          renderEntityList();
          selectEntity(key, { updateHash: false, scroll: false });
          $("#explorer")?.scrollIntoView({ behavior: "smooth", block: "start" });
        }
      } else if (hash.startsWith("concept=")) {
        const id = hash.slice("concept=".length);
        if (conceptById.has(id)) {
          selectConcept(id, { updateHash: false });
          $("#taxonomy")?.scrollIntoView({ behavior: "smooth", block: "start" });
        }
      }
    };
    window.addEventListener("hashchange", parse);
    parse();
  }

  function bindReveal() {
    const items = $$(".reveal");
    if (!items.length) return;
    if (!("IntersectionObserver" in window) || window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
      items.forEach((item) => item.classList.add("is-visible"));
      return;
    }
    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            entry.target.classList.add("is-visible");
            observer.unobserve(entry.target);
          }
        });
      },
      { rootMargin: "0px 0px -8% 0px", threshold: 0.08 }
    );
    items.forEach((item) => observer.observe(item));
    // Safety net: content must never remain invisible if an observer callback
    // is missed (full-page screenshots, embedded browsers, restored tabs).
    window.setTimeout(() => items.forEach((item) => item.classList.add("is-visible")), 1600);
  }

